-- =============================================================================
-- SysConf - Gerenciar arquivos importados (tela "Importacoes")
-- Arquivo : supabase/migrations/20260916000107_importacao_gerenciar.sql
--
-- OBJETIVO (pedido do cliente): uma tela onde ele ve as importacoes feitas,
-- BAIXA o arquivo original, ve informacoes (fabrica, data, quem importou,
-- quantas linhas entraram/foram descartadas) e REMOVE a importacao (apagando
-- os pedidos daquela importacao da base).
--
-- DESENHO:
--   1. `importacao` = cabecalho de cada importacao (um por arquivo importado),
--      com o ARQUIVO ORIGINAL guardado em base64 na propria coluna `conteudo`.
--      Nao usei o Storage do Supabase de proposito: o bucket ficaria acessivel
--      com a chave publica que vai no bundle do site (qualquer um com a chave
--      leria os pedidos dos clientes). Aqui o arquivo fica protegido pela MESMA
--      sessao por token que protege o resto do sistema, e o download passa por
--      RPC. Se um dia o volume crescer muito, migramos para o Storage.
--   2. `pedido.importacao_id` liga cada pedido ao seu cabecalho, com
--      ON DELETE CASCADE: excluir a importacao apaga os pedidos dela.
--   3. BACKFILL: as importacoes antigas (WinForms e a da Romanzza de hoje) viram
--      cabecalhos historicos, com o arquivo sem conteudo (nao temos o original),
--      para a tela ja nascer com o historico visivel.
--
-- PERMISSOES: registrar/listar/baixar = qualquer usuario da empresa (o operador
-- importa). EXCLUIR = so ADMIN (apaga pedidos de verdade).
--
-- COMO APLICAR: Supabase Dashboard -> SQL Editor -> colar TODO este arquivo -> Run.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- 1. CABECALHO DA IMPORTACAO
-- -----------------------------------------------------------------------------
create table if not exists public.importacao (
    id                 bigint    not null generated by default as identity,
    empresa_id         bigint    not null references public.empresa (id) on delete cascade,
    layout_controle    integer   not null references public.layout (controle) on delete cascade,
    nome_arquivo       varchar(255) not null,
    tamanho_bytes      integer   not null default 0,
    codificacao        varchar(20) not null default 'UTF-8',
    linhas_lidas       integer   not null default 0,
    linhas_importadas  integer   not null default 0,
    linhas_descartadas integer   not null default 0,
    usuario_id         bigint,
    usuario_login      varchar(50),
    criado_em          timestamp not null default now(),
    /** Arquivo original em base64 (para o botao "Baixar"). Nulo no historico antigo. */
    conteudo           text,
    constraint pk_importacao primary key (id)
);

comment on table public.importacao is
    'Cabecalho de cada importacao de arquivo: o que foi importado, quando, por quem e o arquivo original.';
comment on column public.importacao.conteudo is
    'Arquivo original em base64 (ate ~4 MB). Nulo quando o arquivo veio do sistema antigo (sem original guardado).';

alter table public.importacao enable row level security;
revoke all on table public.importacao from anon, authenticated;

create index if not exists ix_importacao_empresa_data on public.importacao (empresa_id, criado_em desc);

/* vinculo do pedido com a importacao (excluir a importacao apaga os pedidos) */
alter table public.pedido
    add column if not exists importacao_id bigint references public.importacao (id) on delete cascade;

create index if not exists ix_pedido_importacao on public.pedido (importacao_id);


-- -----------------------------------------------------------------------------
-- 2. BACKFILL: importacoes antigas viram historico
-- -----------------------------------------------------------------------------
insert into public.importacao (
    empresa_id, layout_controle, nome_arquivo, linhas_importadas,
    usuario_login, criado_em, codificacao
)
select p.empresa_id,
       p.idlayout,
       p.arquivo,
       count(*),
       'sistema antigo',
       min(p.datainc),
       'NAO GUARDADO'
from public.pedido p
where p.importacao_id is null
  and p.arquivo is not null
  and btrim(p.arquivo) <> ''
group by p.empresa_id, p.idlayout, p.arquivo;

update public.pedido p
   set importacao_id = i.id
  from public.importacao i
 where p.importacao_id is null
   and i.empresa_id = p.empresa_id
   and i.layout_controle = p.idlayout
   and i.nome_arquivo = p.arquivo;


