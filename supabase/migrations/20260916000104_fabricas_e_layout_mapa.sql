-- -----------------------------------------------------------------------------
-- 1. MAPA DO LAYOUT (uma linha por fabrica)
-- -----------------------------------------------------------------------------
create table if not exists public.layout_mapa (
    id              bigint    not null generated by default as identity,
    empresa_id      bigint    not null references public.empresa (id) on delete cascade,
    layout_controle integer   not null references public.layout (controle) on delete cascade,
    delimitador     varchar(4)  not null default ';',
    linha_inicial   integer     not null default 1,        -- 1 = primeira linha do arquivo
    tem_cabecalho   boolean     not null default false,
    codificacao     varchar(20) not null default 'UTF-8',
    campos          jsonb       not null default '{}'::jsonb,  -- {"etiqueta":6,"produto":3,...}
    criado_em       timestamp   not null default now(),
    atualizado_em   timestamp   not null default now(),
    constraint pk_layout_mapa primary key (id),
    constraint ux_layout_mapa_fabrica unique (layout_controle)  -- decisao 1
);

comment on table public.layout_mapa is
    'Como ler o arquivo de cada fabrica: delimitador, primeira linha util, cabecalho e o mapa campo -> coluna.';
comment on column public.layout_mapa.campos is
    'Indice (0-based) da coluna do arquivo para cada campo: etiqueta, produto, descricao1, qtde, volume, sequencia, pecliente, ordcompra, cliente.';

alter table public.layout_mapa enable row level security;
revoke all on table public.layout_mapa from anon, authenticated;


-- -----------------------------------------------------------------------------
-- 2. HELPERS
-- -----------------------------------------------------------------------------
/** Valida e normaliza o mapa de campos recebido do navegador. */
create or replace function public.layout_campos_validar(p_campos jsonb)
returns jsonb
language plpgsql
immutable
as $$
declare
    v_permitidos text[] := array['ordcompra','cliente','pecliente','produto','descricao1','qtde','etiqueta','volume','sequencia'];
    v_chave text;
    v_valor jsonb;
    v_saida jsonb := '{}'::jsonb;
    v_indice integer;
begin
    if p_campos is null or jsonb_typeof(p_campos) <> 'object' then
        raise exception 'Mapa de colunas invalido.';
    end if;

    for v_chave, v_valor in select * from jsonb_each(p_campos) loop
        if not (v_chave = any (v_permitidos)) then
            raise exception 'Campo desconhecido no layout: %', v_chave;
        end if;
        if v_valor is null or v_valor = 'null'::jsonb then
            continue;
        end if;
        begin
            v_indice := (v_valor #>> '{}')::integer;
        exception when others then
            raise exception 'Coluna invalida para o campo %: %', v_chave, v_valor #>> '{}';
        end;
        if v_indice < 0 or v_indice > 500 then
            raise exception 'Coluna fora do intervalo para o campo %: %', v_chave, v_indice;
        end if;
        v_saida := v_saida || jsonb_build_object(v_chave, v_indice);
    end loop;

    /* a etiqueta e a chave da conferencia: sem ela o layout nao serve */
    if not (v_saida ? 'etiqueta') then
        raise exception 'Escolha qual coluna do arquivo tem a ETIQUETA (codigo de barras).';
    end if;

    return v_saida;
end;
$$;

revoke all on function public.layout_campos_validar(jsonb) from public;


