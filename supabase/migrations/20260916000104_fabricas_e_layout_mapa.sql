/** Lista completa para a tela de fabricas: situacao, pedidos e se tem layout. */
create or replace function public.fabricas_admin(p_token text)
returns table (
    controle       integer,
    nome           varchar,
    ativo          integer,
    pedidos        bigint,
    tem_layout     boolean,
    layout_campos  jsonb,
    layout_delim   varchar
)
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
    v_sessao public.sessao := public.sessao_aberta(p_token);
begin
    perform public.exigir_admin(v_sessao);

    return query
        select l.controle,
               l.nome,
               l.flativo,
               (select count(*) from public.pedido p where p.idlayout = l.controle) as pedidos,
               (m.id is not null) as tem_layout,
               m.campos,
               m.delimitador
        from public.layout l
        left join public.layout_mapa m on m.layout_controle = l.controle
        where l.empresa_id = v_sessao.empresa_id
        order by l.nome;
end;
$$;

/** Cria a fabrica para a empresa da sessao e devolve o `controle` gerado. */
create or replace function public.fabrica_criar(p_token text, p_nome text)
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_sessao public.sessao := public.sessao_aberta(p_token);
    v_nome   text := btrim(coalesce(p_nome, ''));
    v_base   integer;
    v_novo   integer;
begin
    perform public.exigir_admin(v_sessao);

    if length(v_nome) < 2 or length(v_nome) > 60 then
        raise exception 'O nome da fabrica deve ter de 2 a 60 caracteres.';
    end if;
    if exists (
        select 1 from public.layout l
        where l.empresa_id = v_sessao.empresa_id and lower(l.nome) = lower(v_nome)
    ) then
        raise exception 'Ja existe uma fabrica chamada "%" nesta empresa.', v_nome;
    end if;

    /* `controle` e PK GLOBAL: serializa o calculo (dois cadastros simultaneos) */
    perform pg_advisory_xact_lock(hashtext('sysconf.layout.controle'));
    select coalesce(max(l.controle), 0) + 1 into v_novo from public.layout l;

    insert into public.layout (controle, nome, flativo, empresa_id)
    values (v_novo, v_nome, 1, v_sessao.empresa_id);

    return v_novo;
end;
$$;

/** Renomeia e/ou ativa-desativa a fabrica. */
create or replace function public.fabrica_atualizar(
    p_token    text,
    p_controle integer,
    p_nome     text,
    p_ativo    integer
)
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_sessao public.sessao := public.sessao_aberta(p_token);
    v_nome   text := btrim(coalesce(p_nome, ''));
    v_linhas integer;
begin
    perform public.exigir_admin(v_sessao);

    if not exists (
        select 1 from public.layout l
        where l.controle = p_controle and l.empresa_id = v_sessao.empresa_id
    ) then
        raise exception 'Fabrica nao encontrada nesta empresa.' using errcode = 'P0002';
    end if;

    if length(v_nome) < 2 or length(v_nome) > 60 then
        raise exception 'O nome da fabrica deve ter de 2 a 60 caracteres.';
    end if;
    if exists (
        select 1 from public.layout l
        where l.empresa_id = v_sessao.empresa_id
          and lower(l.nome) = lower(v_nome)
          and l.controle <> p_controle
    ) then
        raise exception 'Ja existe uma fabrica chamada "%" nesta empresa.', v_nome;
    end if;
    if coalesce(p_ativo, 1) not in (0, 1) then
        raise exception 'Situacao invalida.';
    end if;

    update public.layout l
       set nome = v_nome, flativo = coalesce(p_ativo, l.flativo)
     where l.controle = p_controle;

    get diagnostics v_linhas = row_count;
    return v_linhas;
end;
$$;

/** Exclui a fabrica - somente se ela nao tiver nenhum pedido importado. */
create or replace function public.fabrica_excluir(p_token text, p_controle integer)
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_sessao public.sessao := public.sessao_aberta(p_token);
    v_pedidos bigint;
    v_linhas  integer;
begin
    perform public.exigir_admin(v_sessao);

    if not exists (
        select 1 from public.layout l
        where l.controle = p_controle and l.empresa_id = v_sessao.empresa_id
    ) then
        raise exception 'Fabrica nao encontrada nesta empresa.' using errcode = 'P0002';
    end if;

    select count(*) into v_pedidos from public.pedido p where p.idlayout = p_controle;
    if v_pedidos > 0 then
        raise exception 'Esta fabrica tem % pedido(s) importado(s). Desative em vez de excluir.', v_pedidos;
    end if;

    delete from public.layout l where l.controle = p_controle;
    get diagnostics v_linhas = row_count;
    return v_linhas;
end;
$$;


