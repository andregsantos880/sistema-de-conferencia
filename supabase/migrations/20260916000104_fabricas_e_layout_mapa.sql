--
-- PROBLEMA: `layout` (fabrica) nascia apenas por SQL ou pelo catalogo do
-- autocadastro, e o mapa de colunas do arquivo de cada fabrica estava no CODIGO
-- do site (web/src/lib/parsers.ts -> PARSERS). Cada fabrica nova exigia deploy.
--
-- SOLUCAO: a empresa (administrador) cadastra a fabrica e define o layout
-- importando um arquivo real, com deteccao automatica de delimitador e ajuste
-- manual (mesma ideia do "Importar dados TXT" do Excel). O mapa fica no banco,
-- em `layout_mapa`, e a importacao passa a usar o layout salvo.
--
-- Decisoes do cliente (16/09/2026):
--   1. uma fabrica = UM layout (variacoes entram como fabricas separadas,
--      igual ao legado: "Italinea" e "Italinea Loja")  -> unique em layout_controle
--   2. arquivo posicional (largura fixa) fica para a fase 2
--   3. so o ADMINISTRADOR cria fabrica e define layout (o operador so importa)
--   4. codificacao: UTF-8 (se o arquivo vier em ANSI, a tela avisa)
--
-- O navegador continua SEM acesso direto as tabelas: escrita e leitura passam
-- por estes RPCs (o GRANT de `layout` para anon/authenticated segue revogado).
--
